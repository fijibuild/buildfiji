#[starlark_value(type = "bazel_module_tags")]
impl<'v> StarlarkValue<'v> for BazelModuleTags {
    fn get_attr(&self, attribute: &str, heap: Heap<'v>) -> Option<Value<'v>> {
        if !self.data.classes.iter().any(|c| c == attribute) {
            return None;
        }
        let module = &self.data.modules[self.index];
        let tags: Vec<Value<'v>> = module
            .tags
            .iter()
            .enumerate()
            .filter(|(_, t)| t.class == attribute)
            .map(|(at, _)| {
                heap.alloc(BazelModuleTag {
                    data: Arc::clone(&self.data),
                    module: self.index,
                    tag: at,
                })
            })
            .collect();
        Some(heap.alloc(AllocList(tags)))
    }

    fn dir_attr(&self) -> Vec<String> {
        self.data.classes.clone()
    }
}

