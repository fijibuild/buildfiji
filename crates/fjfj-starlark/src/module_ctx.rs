//! `module_ctx` and running a module extension (buildfiji-mum.8.4).
//!
//! [`run_module_extension`] runs the implementation of a `module_extension()`
//! (buildfiji-mum.8.1) over what the modules of the graph wrote for it,
//! and returns the repositories it made by calling repository rules. The
//! local operations are `repository_ctx`'s (buildfiji-mum.8.2), shared; the
//! rest is what is specific to extensions.
//!
//! What Bazel 9.2.0 does, all read off probes:
//!
//! - **Tags.** Every tag a module wrote is checked against its tag class
//!   before the implementation runs, and an error says where the tag was
//!   written: `in 'tag' tag, unknown attribute 'x' provided`, `... mandatory
//!   attribute 'x' isn't being specified`, `... expected value of type 'string'
//!   for attribute 'x', but got 1 (int)`; a tag of a class the extension does
//!   not have is `The module extension defined at FILE:L:C does not have a tag
//!   class named X, but its use is attempted at MODULE.bazel:L:C`. A tag gets
//!   the default of each attribute it left out.
//! - **`mctx.modules`** is the modules that use the extension, each a
//!   `bazel_module` with `name`, `version` (`""` for none), `is_root` and
//!   `tags`, whose attribute for each tag class of the extension (whether or
//!   not it was used) is the list of that module's tags of the class in
//!   written order. A tag prints as `'tag' tag at MODULE.bazel:3:8`.
//!   `mctx.is_dev_dependency(tag)` and `mctx.root_module_has_non_dev_dependency`
//!   say what `dev_dependency` said.
//! - **Repositories.** Calling a repository rule from the implementation
//!   makes one: the name must be a string (`expected string for attribute
//!   'name', got 'NoneType'`) of letters, digits and `-_.` starting with a
//!   letter or digit, not used already by the extension (`A repo named a is
//!   already generated by this module extension at FILE:L:C`), and every other
//!   attribute must be one the rule has, of the right type (`in call to 'repo'
//!   repo rule with name 'a', unknown attribute 'x' provided`); the call
//!   returns `None`.
//! - **The working directory** is one of the extension's own, which a file
//!   written with `mctx.file` goes in and a relative path is relative to. A
//!   label in the main repository is the file, and `mctx.watch` of a path
//!   under the working directory is refused, as for a repository rule.
//! - `mctx.facts` prints `Facts({})`; `mctx.extension_metadata(...)` returns an
//!   inert object.

