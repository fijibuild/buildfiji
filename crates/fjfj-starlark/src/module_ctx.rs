/// A value in a tag a module wrote: the data a `MODULE.bazel` can hold.
#[derive(Debug, Clone, PartialEq)]
pub enum TagValue {
    None,
    Bool(bool),
    Int(i64),
    String(String),
    List(Vec<TagValue>),
    Dict(Vec<(TagValue, TagValue)>),
}

impl TagValue {
    /// The value as Starlark writes it.
    fn repr(&self) -> String {
        match self {
            TagValue::None => "None".to_owned(),
            TagValue::Bool(true) => "True".to_owned(),
            TagValue::Bool(false) => "False".to_owned(),
            TagValue::Int(i) => i.to_string(),
            TagValue::String(s) => format!("{s:?}"),
            TagValue::List(items) => format!(
                "[{}]",
                items
                    .iter()
                    .map(TagValue::repr)
                    .collect::<Vec<_>>()
                    .join(", ")
            ),
            TagValue::Dict(items) => format!(
                "{{{}}}",
                items
                    .iter()
                    .map(|(k, v)| format!("{}: {}", k.repr(), v.repr()))
                    .collect::<Vec<_>>()
                    .join(", ")
            ),
        }
    }

    fn type_name(&self) -> &'static str {
        match self {
            TagValue::None => "NoneType",
            TagValue::Bool(_) => "bool",
            TagValue::Int(_) => "int",
            TagValue::String(_) => "string",
            TagValue::List(_) => "list",
            TagValue::Dict(_) => "dict",
        }
    }

    /// Read a Starlark value, if it is one the data can hold.
    pub(crate) fn from_value(value: Value<'_>) -> Option<TagValue> {
        if value.is_none() {
            return Some(TagValue::None);
        }
        if let Some(b) = value.unpack_bool() {
            return Some(TagValue::Bool(b));
        }
        if let Some(s) = value.unpack_str() {
            return Some(TagValue::String(s.to_owned()));
        }
        // A `Label` is the canonical label it stands for.
        if let Some(label) = value.downcast_ref::<crate::label::StarlarkLabel>() {
            return Some(TagValue::String(label.canonical()));
        }
        if let Some(i) = value.unpack_i32() {
            return Some(TagValue::Int(i.into()));
        }
        if let Some(list) = ListRef::from_value(value) {
            let items = list
                .iter()
                .map(TagValue::from_value)
                .collect::<Option<Vec<_>>>()?;
            return Some(TagValue::List(items));
        }
        if let Some(tuple) = TupleRef::from_value(value) {
            let items = tuple
                .iter()
                .map(TagValue::from_value)
                .collect::<Option<Vec<_>>>()?;
            return Some(TagValue::List(items));
        }
        if let Some(dict) = DictRef::from_value(value) {
            let items = dict
                .iter()
                .map(|(k, v)| Some((TagValue::from_value(k)?, TagValue::from_value(v)?)))
                .collect::<Option<Vec<_>>>()?;
            return Some(TagValue::Dict(items));
        }
        None
    }
}

