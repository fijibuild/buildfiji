// ---- converting what was written ------------------------------------------------------

fn label_in(text: &str, repo: &str, mappings: &RepoMappings) -> Result<Label, LabelParseError> {
    resolve_label(
        text,
        fjfj_graph::LabelContext { repo, package: "" },
        repo,
        mappings,
    )
    .map(crate::label::StarlarkLabel::into_label)
}

/// `value` as an attribute of type `ty`, or the words for why not.
pub(crate) fn plain_to_attr(
    ty: AttrType,
    value: &TagValue,
    repo: &str,
    mappings: &RepoMappings,
) -> Result<RepoAttr, String> {
    let mismatch = || format!("{} ({})", value.repr(), value.type_name());
    let strings = |items: &[TagValue]| -> Option<Vec<String>> {
        items
            .iter()
            .map(|i| match i {
                TagValue::String(s) => Some(s.clone()),
                _ => None,
            })
            .collect()
    };
    let label = |text: &str| label_in(text, repo, mappings).map_err(|e| e.to_string());
    let fail = || Err(mismatch());
    Ok(match (ty, value) {
        (AttrType::Bool, TagValue::Bool(b)) => RepoAttr::Bool(*b),
        (AttrType::Int, TagValue::Int(i)) => RepoAttr::Int(*i),
        (AttrType::String, TagValue::String(s)) => RepoAttr::String(s.clone()),
        (AttrType::Label, TagValue::String(s)) => RepoAttr::Label(label(s)?),
        (AttrType::StringList, TagValue::List(items)) => match strings(items) {
            Some(items) => RepoAttr::StringList(items),
            None => return fail(),
        },
        (AttrType::IntList, TagValue::List(items)) => {
            let ints: Option<Vec<i64>> = items
                .iter()
                .map(|i| match i {
                    TagValue::Int(i) => Some(*i),
                    _ => None,
                })
                .collect();
            match ints {
                Some(items) => RepoAttr::IntList(items),
                None => return fail(),
            }
        }
        (AttrType::LabelList, TagValue::List(items)) => match strings(items) {
            Some(items) => RepoAttr::LabelList(
                items
                    .iter()
                    .map(|s| label(s))
                    .collect::<Result<Vec<_>, _>>()?,
            ),
            None => return fail(),
        },
        (AttrType::StringDict, TagValue::Dict(items)) => {
            let pairs: Option<Vec<(String, String)>> = items
                .iter()
                .map(|(k, v)| match (k, v) {
                    (TagValue::String(k), TagValue::String(v)) => Some((k.clone(), v.clone())),
                    _ => None,
                })
                .collect();
            match pairs {
                Some(pairs) => RepoAttr::StringDict(pairs),
                None => return fail(),
            }
        }
        (AttrType::StringKeyedLabelDict, TagValue::Dict(items)) => {
            let mut pairs = Vec::new();
            for (k, v) in items {
                match (k, v) {
                    (TagValue::String(k), TagValue::String(v)) => {
                        pairs.push((k.clone(), label(v)?));
                    }
                    _ => return fail(),
                }
            }
            RepoAttr::StringKeyedLabelDict(pairs)
        }
        (AttrType::LabelKeyedStringDict, TagValue::Dict(items)) => {
            let mut pairs = Vec::new();
            for (k, v) in items {
                match (k, v) {
                    (TagValue::String(k), TagValue::String(v)) => {
                        pairs.push((label(k)?, v.clone()));
                    }
                    _ => return fail(),
                }
            }
            RepoAttr::LabelKeyedStringDict(pairs)
        }
        (AttrType::LabelListDict, TagValue::Dict(items)) => {
            let mut pairs = Vec::new();
            for (k, v) in items {
                match (k, v) {
                    (TagValue::String(k), TagValue::List(v)) => {
                        let labels = strings(v)
                            .ok_or_else(mismatch)?
                            .iter()
                            .map(|s| label(s))
                            .collect::<Result<Vec<_>, _>>()?;
                        pairs.push((k.clone(), labels));
                    }
                    _ => return fail(),
                }
            }
            RepoAttr::LabelListDict(pairs)
        }
        (AttrType::StringListDict, TagValue::Dict(items)) => {
            let pairs: Option<Vec<(String, Vec<String>)>> = items
                .iter()
                .map(|(k, v)| match (k, v) {
                    (TagValue::String(k), TagValue::List(v)) => Some((k.clone(), strings(v)?)),
                    _ => None,
                })
                .collect();
            match pairs {
                Some(pairs) => RepoAttr::StringListDict(pairs),
                None => return fail(),
            }
        }
        _ => return fail(),
    })
}

/// The attribute definitions of a tag class or repository rule: for each name
/// its type, default and whether it is mandatory.
struct AttrSpec {
    name: String,
    ty: AttrType,
    default: Option<AttrValue>,
    mandatory: bool,
}

fn specs_of(attrs: Option<Value<'_>>) -> Vec<AttrSpec> {
    let Some(dict) = attrs.and_then(DictRef::from_value) else {
        return Vec::new();
    };
    dict.iter()
        .filter_map(|(name, descriptor)| {
            let view = attribute_view(descriptor)?;
            Some(AttrSpec {
                name: name.unpack_str()?.to_owned(),
                ty: view.def.ty,
                default: view.def.default.clone(),
                mandatory: view.def.flags.contains(&AttrFlag::Mandatory),
            })
        })
        .collect()
}

fn default_attr(spec: &AttrSpec) -> Option<RepoAttr> {
    let Some(value) = spec.default.clone().or_else(|| spec.ty.zero()) else {
        return Some(RepoAttr::None);
    };
    Some(match value {
        AttrValue::Bool(b) => RepoAttr::Bool(b),
        AttrValue::Int(i) => RepoAttr::Int(i64::from(i)),
        AttrValue::String(s) => RepoAttr::String(s),
        AttrValue::StringList(items) => RepoAttr::StringList(items),
        AttrValue::IntList(items) => RepoAttr::IntList(items.into_iter().map(i64::from).collect()),
        AttrValue::Label(label) => RepoAttr::Label(label),
        AttrValue::LabelList(labels) => RepoAttr::LabelList(labels),
        AttrValue::StringDict(items) => RepoAttr::StringDict(items),
        AttrValue::StringListDict(items) => RepoAttr::StringListDict(items),
        AttrValue::StringKeyedLabelDict(items) => RepoAttr::StringKeyedLabelDict(items),
        AttrValue::LabelKeyedStringDict(items) => RepoAttr::LabelKeyedStringDict(items),
        AttrValue::LabelListDict(items) => RepoAttr::LabelListDict(items),
        _ => return None,
    })
}

/// Check a tag against its class and fill in what it left out.
/// The strings of a tag attribute of type `ty` that are read as labels.
fn label_texts(ty: AttrType, value: &TagValue) -> Vec<&str> {
    fn text(v: &TagValue) -> Option<&str> {
        match v {
            TagValue::String(s) => Some(s.as_str()),
            _ => None,
        }
    }
    match (ty, value) {
        (AttrType::Label, v) => text(v).into_iter().collect(),
        (AttrType::LabelList, TagValue::List(items)) => {
            items.iter().filter_map(|i| text(i)).collect()
        }
        (AttrType::StringKeyedLabelDict | AttrType::LabelListDict, TagValue::Dict(items)) => {
            let mut out = Vec::new();
            for (_, v) in items {
                match v {
                    TagValue::List(items) => out.extend(items.iter().filter_map(|i| text(i))),
                    other => out.extend(text(other)),
                }
            }
            out
        }
        (AttrType::LabelKeyedStringDict, TagValue::Dict(items)) => {
            items.iter().filter_map(|(k, _)| text(k)).collect()
        }
        _ => Vec::new(),
    }
}

fn check_tag(
    class_attrs: &[AttrSpec],
    tag: &TagUse,
    repo: &str,
    mappings: &RepoMappings,
    recorder: &crate::repo_ctx::Recorder,
) -> Result<Vec<(String, RepoAttr)>, String> {
    let prefix = format!("in '{}' tag, ", tag.class);
    for (name, _) in &tag.attrs {
        if !class_attrs.iter().any(|a| &a.name == name) {
            return Err(format!("{prefix}unknown attribute '{name}' provided"));
        }
    }
    let mut out = Vec::new();
    for spec in class_attrs {
        match tag.attrs.iter().find(|(n, _)| n == &spec.name) {
            Some((_, value)) => {
                let converted = plain_to_attr(spec.ty, value, repo, mappings).map_err(|why| {
                    format!(
                        "{prefix}expected value of type '{}' for attribute '{}', but got {why}",
                        spec.ty.name(),
                        spec.name
                    )
                })?;
                // The repo names a label in a tag uses are looked up in the
                // mapping of the module that wrote it.
                for text in label_texts(spec.ty, value) {
                    if let Some(apparent) = crate::label::apparent_repo(text) {
                        recorder.push(crate::repo_ctx::RecordedInput::RepoMapping {
                            repo: repo.to_owned(),
                            apparent: apparent.to_owned(),
                            canonical: mappings
                                .find_apparent(repo, apparent)
                                .unwrap_or_else(|| "\\0".to_owned()),
                        });
                    }
                }
                out.push((spec.name.clone(), converted));
            }
            None if spec.mandatory => {
                return Err(format!(
                    "{prefix}mandatory attribute '{}' isn't being specified",
                    spec.name
                ));
            }
            None => {
                if let Some(default) = default_attr(spec) {
                    out.push((spec.name.clone(), default));
                }
            }
        }
    }
    Ok(out)
}

