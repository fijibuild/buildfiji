/// Why a repository could not be made: Bazel's message for it.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
#[error("{message}")]
pub struct FetchError {
    pub message: String,
}

fn failed<T>(message: impl Into<String>) -> Result<T, FetchError> {
    Err(FetchError {
        message: message.into(),
    })
}

/// What making the repositories of a workspace needs.
pub struct Options {
    /// The main repository's directory.
    pub workspace_root: PathBuf,
    /// Where extensions work (`modextwd`) and repositories are made
    /// (`external`).
    pub output_base: PathBuf,
    /// The client's environment.
    pub environ: BTreeMap<String, String>,
    /// How `http` and `https` URLs are fetched; none means they cannot be.
    pub downloader: Option<Arc<dyn Downloader>>,
    /// The repository cache directory, which holds `content_addressable/`.
    pub repository_cache: Option<PathBuf>,
    /// `--distdir`: where a download's file may be found by its name.
    pub distdirs: Vec<PathBuf>,
    /// The registries the modules of the graph came from: how a module's
    /// repository is made is in its `source.json`.
    pub registries: Vec<Registry>,
    /// The `facts` a previous run kept, as the lockfile has them: an extension's
    /// id (`//:ext.bzl%name`) and its facts as a JSON object.
    pub facts: Vec<(String, Json)>,
    /// `--override_repository`: the name the main repository sees a repo by,
    /// and the directory that is the repo instead (relative to the workspace).
    pub repo_overrides: Vec<(String, PathBuf)>,
}

/// A repository to make: a rule and what it is called with.
struct Generated {
    repo: GeneratedRepo,
    /// What a `use_repo_rule` call or a module's source gave, not yet read as
    /// the rule's types: that needs the rule's `.bzl` loaded.
    raw_attrs: Option<Vec<(String, TagValue)>>,
    /// The extension that made it, `@@//:ext.bzl%ext`; empty for a module's
    /// own repository and for a `use_repo_rule`.
    extension: String,
}

#[derive(Default)]
struct State {
    /// What each repo calls the others; grows as extensions run.
    mappings: Arc<RepoMappings>,
    /// The repositories that have been made, by canonical name.
    lookups: HashMap<String, Arc<PackageLookup>>,
    /// Repositories extensions generated, by canonical name.
    generated: BTreeMap<String, Generated>,
    /// The extensions that have run, and those running now.
    ran: BTreeSet<usize>,
    running: BTreeMap<usize, std::thread::ThreadId>,
    /// Repositories being made now, and by which thread.
    making: BTreeMap<String, std::thread::ThreadId>,
    /// Repos replaced by a directory, by canonical name.
    overridden: BTreeMap<String, PathBuf>,
    /// What each extension that ran gives `MODULE.bazel.lock`.
    locked: Vec<LockedExtension>,
    /// The `facts` extensions kept, by extension id.
    facts: Vec<(String, Json)>,
    /// What was worth a warning, each as Bazel words it after `WARNING: `.
    warnings: Vec<String>,
}

/// One extension's entry in `MODULE.bazel.lock`'s `moduleExtensions`.
#[derive(Debug, Clone, PartialEq)]
pub struct LockedExtension {
    /// `//:ext.bzl%name`, or `@@repo//:ext.bzl%name` from another repository.
    pub id: String,
    /// `general`, or `os:linux`, `arch:amd64`, `os:linux,arch:amd64` for an
    /// extension that depends on them.
    pub factors: String,
    /// What goes under the factors: `bzlTransitiveDigest`, `usagesDigest`,
    /// `recordedInputs` and `generatedRepoSpecs`.
    pub entry: Json,
}

struct Inner {
    options: Options,
    resolution: Resolution,
    extensions: Vec<ExtensionInstance>,
    loader: OnceLock<BzlLoader>,
    state: Mutex<State>,
    /// Signalled when a repository or extension stops being made, for the
    /// threads that wait for it.
    progress: std::sync::Condvar,
    /// What extensions and rules print, in order, until the call that made
    /// them hands it on.
    prints: Prints,
}

/// What was printed, kept for whoever asked for the work: an extension may
/// run because a file was loaded, far from the call that has a print handler.
#[derive(Default)]
struct Prints(Mutex<Vec<String>>);

impl PrintHandler for Prints {
    fn println(&self, text: &str) -> starlark::Result<()> {
        self.0.lock().unwrap().push(text.to_owned());
        Ok(())
    }
}

impl Prints {
    /// Hand everything printed so far to `print`.
    fn hand_on(&self, print: Option<&dyn PrintHandler>) {
        let printed = std::mem::take(&mut *self.0.lock().unwrap());
        if let Some(print) = print {
            for text in printed {
                let _ = print.println(&text);
            }
        }
    }
}

struct Provider(Weak<Inner>);

impl RepoProvider for Provider {
    fn lookup(&self, repo: &str) -> Result<Option<Arc<PackageLookup>>, String> {
        let inner = self.0.upgrade().ok_or("the repositories are gone")?;
        inner.lookup(repo).map_err(|e| e.message)
    }

    fn mappings(&self) -> Arc<RepoMappings> {
        match self.0.upgrade() {
            Some(inner) => inner.state.lock().unwrap().mappings.clone(),
            None => Arc::default(),
        }
    }
}

/// The repositories of a workspace.
pub struct Repos {
    inner: Arc<Inner>,
}

fn label_text(label: &Label) -> String {
    format!("@@{}//{}:{}", label.repo, label.package, label.name)
}

/// The label of `//pkg:file.bzl` in `repo`.
fn bzl_label(repo: &str, rest: &str) -> Label {
    let rest = rest.strip_prefix("//").unwrap_or(rest);
    let (package, name) = rest.split_once(':').unwrap_or(("", rest));
    Label {
        repo: repo.to_owned(),
        package: package.to_owned(),
        name: name.to_owned(),
    }
}

impl Repos {
    /// The repositories of the workspace whose root module is `root`, and
    /// which has no other module.
    pub fn new(options: Options, root: Module) -> Result<Repos, FetchError> {
        Repos::from_resolution(options, Resolution::root_only(root))
    }

    /// The repositories of the workspace whose module graph is `resolution`.
    pub fn from_resolution(options: Options, resolution: Resolution) -> Result<Repos, FetchError> {
        // A `//...` walk does not enter the convenience symlinks, which lead into
        // the output base: `bazel-bin`, `bazel-out`, `bazel-testlogs` and
        // `bazel-<workspace>`.
        let workspace_dir = options
            .workspace_root
            .file_name()
            .map(|n| n.to_string_lossy().into_owned())
            .unwrap_or_default();
        let lookup = PackageLookup::new(&options.workspace_root)
            .map_err(|e| FetchError {
                message: e.to_string(),
            })?
            .with_skipped_root_dirs([
                "bazel-bin".to_owned(),
                "bazel-out".to_owned(),
                "bazel-testlogs".to_owned(),
                "bazel-genfiles".to_owned(),
                format!("bazel-{workspace_dir}"),
            ]);
        // `@bazel_tools` is served from the output base, where its files are put.
        let tools_dir = options.output_base.join("external").join("bazel_tools");
        materialize_bazel_tools(&tools_dir).map_err(|e| FetchError {
            message: format!("cannot write @bazel_tools to {}: {e}", tools_dir.display()),
        })?;
        let tools_lookup = PackageLookup::new(&tools_dir).map_err(|e| FetchError {
            message: e.to_string(),
        })?;
        let mut mappings = RepoMappings::from_repos(resolution.repo_mappings());
        if !resolution.selection.keys().any(|k| k.name == "bazel_tools") {
            mappings.insert(
                "bazel_tools",
                [("bazel_tools".to_owned(), "bazel_tools".to_owned())],
            );
        }
        let extensions = resolution.extensions();
        // The names are the main repository's, and an empty one names nothing.
        let mut overridden = BTreeMap::new();
        for (name, path) in &options.repo_overrides {
            if name.is_empty() {
                continue;
            }
            let Some(canonical) = mappings.find_apparent("", name) else {
                return failed(format!(
                    "no repository visible as '@{name}' from the main repository, but overridden \
                     with --override_repository. Use --inject_repository to add new repositories."
                ));
            };
            overridden.insert(canonical, options.workspace_root.join(path));
        }
        let mut state = State {
            mappings: Arc::new(mappings),
            overridden,
            ..State::default()
        };
        state.lookups.insert(String::new(), Arc::new(lookup));
        state
            .lookups
            .insert("bazel_tools".to_owned(), Arc::new(tools_lookup));
        let inner = Arc::new(Inner {
            options,
            resolution,
            extensions,
            loader: OnceLock::new(),
            state: Mutex::new(state),
            progress: std::sync::Condvar::new(),
            prints: Prints::default(),
        });
        let loader = BzlLoader::with_provider(Box::new(Provider(Arc::downgrade(&inner))), true);
        let _ = inner.loader.set(loader);
        inner.note_repo_rules();
        Ok(Repos { inner })
    }

    /// Run every extension of the graph, in the order it is first used.
    /// `print` gets what they print.
    pub fn run_extensions(&mut self, print: Option<&dyn PrintHandler>) -> Result<(), FetchError> {
        let mut result = Ok(());
        for at in 0..self.inner.extensions.len() {
            result = self.inner.ensure_ran(at);
            if result.is_err() {
                break;
            }
        }
        self.inner.prints.hand_on(print);
        result
    }

    /// What the root module's `use_repo`s name, and the repository each is.
    pub fn imports(&self) -> Vec<(String, String)> {
        let inner = &self.inner;
        let root = &inner.resolution.root;
        let state = inner.state.lock().unwrap();
        let mapping = inner
            .resolution
            .repo_mappings()
            .into_iter()
            .find(|(repo, _)| repo.is_empty())
            .map(|(_, rows)| rows)
            .unwrap_or_default();
        drop(state);
        let mut found = Vec::new();
        for extension in &inner.extensions {
            for (key, index) in &extension.usages {
                if !key.is_root() {
                    continue;
                }
                for (local, _) in &root.extension_usages[*index].imports {
                    if let Some((_, canonical)) = mapping.iter().find(|(n, _)| n == local) {
                        found.push((local.clone(), canonical.clone()));
                    }
                }
            }
        }
        found
    }

    /// The canonical name of the repo the main repository calls `apparent` (what
    /// `@apparent` means there), if it calls one that.
    pub fn main_repo_canonical(&self, apparent: &str) -> Option<String> {
        self.inner
            .state
            .lock()
            .unwrap()
            .mappings
            .find_apparent("", apparent)
    }

    /// `register_toolchains` patterns, with the repo of the module that wrote each.
    pub fn registered_toolchains(&self) -> Vec<(String, String)> {
        self.inner.resolution.registered_toolchains()
    }

    /// `register_execution_platforms` patterns, likewise.
    pub fn registered_execution_platforms(&self) -> Vec<(String, String)> {
        self.inner.resolution.registered_execution_platforms()
    }

    /// The canonical name of the repository of the selected module `name`.
    pub fn module_repo(&self, name: &str) -> Option<String> {
        let resolution = &self.inner.resolution;
        resolution
            .selection
            .keys()
            .find(|key| key.name == name && !key.is_root())
            .map(|key| resolution.canonical_name_of(key))
    }

    /// Every repository a fetch of everything makes, in the order modules and
    /// extensions come: the selected modules' (not the main repository nor
    /// `bazel_tools`, which is served from the output base), then what the
    /// extensions that have run generated.
    pub fn all_repos(&self) -> Vec<String> {
        let inner = &self.inner;
        let mut repos: Vec<String> = inner
            .resolution
            .selection
            .keys()
            .filter(|key| !key.is_root() && key.name != "bazel_tools")
            .map(|key| inner.resolution.canonical_name_of(key))
            .collect();
        repos.extend(inner.state.lock().unwrap().generated.keys().cloned());
        repos
    }

    /// The warnings there were so far, each as Bazel words it after `WARNING: `.
    pub fn warnings(&self) -> Vec<String> {
        self.inner.state.lock().unwrap().warnings.clone()
    }

    /// The `facts` the extensions that ran kept: an extension id and what it kept.
    pub fn locked_facts(&self) -> Vec<(String, Json)> {
        self.inner.state.lock().unwrap().facts.clone()
    }

    /// What the extensions that have run give `MODULE.bazel.lock`.
    pub fn locked_extensions(&self) -> Vec<LockedExtension> {
        self.inner.state.lock().unwrap().locked.clone()
    }

    /// The canonical names of the repositories extensions generated.
    pub fn generated(&self) -> impl Iterator<Item = String> {
        let names: Vec<String> = self
            .inner
            .state
            .lock()
            .unwrap()
            .generated
            .iter()
            .filter(|(_, g)| !g.repo.rule.is_empty())
            .map(|(name, _)| name.clone())
            .collect();
        names.into_iter()
    }

    /// Make the repository `name` (a canonical name), running its rule, and
    /// return its directory.
    pub fn fetch(
        &self,
        name: &str,
        print: Option<&dyn PrintHandler>,
    ) -> Result<PathBuf, FetchError> {
        let inner = &self.inner;
        let result = (|| {
            if !inner.is_repo(name)
                && let Some(at) = inner.extension_of_repo(name)
            {
                inner.ensure_ran(at)?;
            }
            inner.make(name)
        })();
        inner.prints.hand_on(print);
        result?;
        Ok(inner.options.output_base.join("external").join(name))
    }

    /// The extension that generated `name`, `@@//:ext.bzl%ext`.
    pub fn extension_of(&self, name: &str) -> Option<String> {
        let state = self.inner.state.lock().unwrap();
        state.generated.get(name).map(|g| g.extension.clone())
    }

    /// The directory of the main repository.
    pub fn workspace_root(&self) -> &Path {
        &self.inner.options.workspace_root
    }

    /// The loader the repositories are read through.
    pub fn loader(&self) -> &BzlLoader {
        self.inner.loader()
    }
}

impl fjfj_loading::PackageSource for Repos {
    fn lookup(&self, repo: &str) -> Result<Arc<PackageLookup>, String> {
        match self.inner.lookup(repo) {
            Ok(Some(lookup)) => Ok(lookup),
            Ok(None) => Err(format!("Repository '@@{repo}' is not defined")),
            Err(e) => Err(e.message),
        }
    }

    fn package(
        &self,
        repo: &str,
        package: &str,
    ) -> Result<Arc<fjfj_graph::package::Package>, String> {
        self.loader()
            .load_package(repo, package)
            .map(|loaded| Arc::new(loaded.package))
            .map_err(|e| e.to_string())
    }
}

